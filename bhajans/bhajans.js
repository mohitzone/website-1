const collator = new Intl.Collator("hi");
const groupsElement = document.getElementById("song-groups");
const searchInput = document.getElementById("bhajan-search");
const statusElement = document.getElementById("search-status");
const emptyState = document.getElementById("empty-state");
const detailElement = document.getElementById("song-detail");
const detailType = document.getElementById("detail-type");
const detailTitle = document.getElementById("detail-title");
const detailTransliteration = document.getElementById("detail-transliteration");
const detailLyrics = document.getElementById("detail-lyrics");
const detailBack = document.getElementById("detail-back");
let selectedSong = null;

function normalizeText(text) {
  return text.normalize("NFC").toLocaleLowerCase("hi").replace(/[।॥.,!?;:'"“”‘’()-]/g, " ").replace(/\s+/g, " ").trim();
}

function renderSongs(query = "") {
  const search = normalizeText(query);
  const matches = songs.filter(song => normalizeText([
    song.title,
    song.transliteration,
    song.indexTitle,
    song.lyrics,
    song.type
  ].join(" ")).includes(search));
  const types = ["आरती", "भजन"];
  groupsElement.replaceChildren();

  types.forEach(type => {
    const typeSongs = matches
      .filter(song => song.type === type)
      .sort((first, second) => collator.compare(first.indexTitle, second.indexTitle));
    if (!typeSongs.length) return;

    const section = document.createElement("section");
    section.className = "group";
    const heading = document.createElement("h2");
    heading.textContent = type;
    const list = document.createElement("div");
    list.className = "song-list";
    section.append(heading);

    typeSongs.forEach(song => {
      const button = document.createElement("button");
      button.className = "song-button";
      button.type = "button";
      button.textContent = song.title;
      button.setAttribute("aria-pressed", String(selectedSong === song));
      button.addEventListener("click", () => showSong(song));
      list.append(button);
    });

    section.append(list);
    groupsElement.append(section);
  });

  emptyState.hidden = matches.length > 0;
  detailElement.hidden = !selectedSong || !matches.includes(selectedSong);
  statusElement.textContent = search
    ? `${matches.length} शीर्षक मिले`
    : `${songs.length} शीर्षक`;
}

function showSong(song) {
  selectedSong = song;
  detailType.textContent = song.type;
  detailTitle.textContent = song.title;
  detailTransliteration.textContent = song.transliteration;
  detailLyrics.textContent = song.lyrics;
  detailElement.hidden = false;
  renderSongs(searchInput.value);
  detailElement.scrollIntoView({ behavior: "smooth", block: "start" });
}

searchInput.addEventListener("input", event => {
  selectedSong = null;
  renderSongs(event.target.value);
});
detailBack.addEventListener("click", () => {
  detailElement.hidden = true;
  selectedSong = null;
  renderSongs(searchInput.value);
});
renderSongs();

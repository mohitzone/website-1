document.addEventListener("DOMContentLoaded", () => {
  const calendarContainer = document.querySelector(".monthly-calendar");
  window.calendar.forEach(m => {
    const block = document.createElement("div");
    block.classList.add("month-block");
    block.innerHTML = `
      <h4>${m.month} ${m.year || ""}</h4>
      <ul>
        ${m.events.map(ev => 
          `<li>
            <strong>${ev.day}${ev.weekday ? " (" + ev.weekday + ")" : ""}</strong> – ${ev.title}
          </li>`
        ).join("")}
      </ul>
    `;
    calendarContainer.appendChild(block);
  });
});